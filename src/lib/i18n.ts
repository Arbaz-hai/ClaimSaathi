export function t(
  lang: Lang,
  key: string,
  vars?: Record<string, string | number>
): string {
  const dict = lang === 'hi' ? hi : en;
  let s = dict[key] ?? en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) {
      s = s.split(`{${k}}`).join(String(v));
    }
  }
  return s;
}

/** Like `t`, but falls back to `fallback` (instead of the raw key). */
export function tOr(
  lang: Lang,
  key: string,
  fallback: string,
  vars?: Record<string, string | number>
): string {
  const dict = lang === 'hi' ? hi : en;
  const found = dict[key] ?? en[key];
  if (!found) return fallback;
  return t(lang, key, vars);
}
